import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";

const required = ["src/lib/brand.ts", "src/app/.well-known/kannagi-release.json/route.ts", "public/favicon.ico", "public/brand/garage-link/og-1200x630.png", "public/brand/garage-link/pwa-192.png", "public/brand/garage-link/pwa-512.png"];
for (const path of required) assert.ok(existsSync(path), `missing ${path}`);
const og = readFileSync("public/brand/garage-link/og-1200x630.png");
assert.equal(og.readUInt32BE(16), 1200); assert.equal(og.readUInt32BE(20), 630);
assert.match(readFileSync("src/app/layout.tsx", "utf8"), /summary_large_image/);
const layout = readFileSync("src/app/layout.tsx", "utf8");
assert.match(layout, /: \{ index: true, follow: true \}/);
assert.match(layout, /locale: "ja_JP"/);
const related = readFileSync("src/lib/related-services.ts", "utf8");
for (const name of ["L-LINK", "AFTERCARE LINK", "TurnKey LINK", "L-touring"]) assert.match(related, new RegExp(name));
assert.equal((related.match(/name:/g) ?? []).length, 4);
assert.match(readFileSync("src/components/landing/GarageLandingPage.tsx", "utf8"), /RELATED_SERVICES/);
assert.match(readFileSync("src/components/login-top/LoginTopPage.tsx", "utf8"), /RELATED_SERVICES/);
const middleware = readFileSync("src/middleware.ts", "utf8");
for (const path of ["/.well-known/kannagi-release.json", "/manifest.webmanifest"]) assert.ok(middleware.includes(path));
const manifest = readFileSync("src/app/manifest.ts", "utf8");
for (const key of ["start_url", "display", "background_color", "theme_color", "pwa192", "pwa512"]) assert.match(manifest, new RegExp(key));
console.log("brand release contract passed");
